package hosted

import (
	"encoding/json"
	"fmt"

	"gopkg.in/yaml.v3"
)

// SMTPSecretName holds the environment's SES SMTP password for the control
// plane's mail sender (DES-HOR-593-06).
const (
	SMTPSecretName = "iterabase-smtp" //nolint:gosec // Secret name, not a credential
	SMTPSecretKey  = "smtp-password"
)

// CloudflareSecretName and CloudflareSecretKey are the Secret external-dns and
// the Let's Encrypt DNS-01 issuer share (charts: cert-issuers, external-dns).
const (
	CloudflareSecretName = "cloudflare-api-token" //nolint:gosec // Secret name, not a credential
	CloudflareSecretKey  = "api-token"
)

// Hostnames are one label below the hosted zone, the depth Cloudflare
// Universal SSL covers (DES-HOR-601-03).
func (c *Contract) AppHost(name string) string     { return name + "." + c.HostedDomain }
func (c *Contract) GatewayHost(name string) string { return name + "-gateway." + c.HostedDomain }

// InstallationValues are the Helm values that are facts of this environment,
// not overlay choices: the controller's cluster identity and environment tag,
// the VPC and region, the origin-pull CA, the public hostnames and the DNS
// zone filter. Forge applies them after the overlay's value files, so an
// overlay cannot point an environment at another environment's resources. The
// hosted edge preset itself (NLB annotations, TLS issuer, enabled components)
// is overlay base content (bases/hosted/values.yaml).
func (c *Contract) InstallationValues(name, smtpUsername string) ([]byte, error) {
	values := map[string]any{
		"global": map[string]any{
			"originPull": map[string]any{"caCert": c.OriginPullCACert},
		},
		"aws-load-balancer-controller": map[string]any{
			"region":      c.Region,
			"clusterName": name,
			"vpcId":       c.VPCID,
			"defaultTags": map[string]string{c.EnvTagKey: name},
		},
		"external-dns": map[string]any{
			"domainFilters": []string{c.HostedDomain + "."},
		},
		"control-plane": map[string]any{
			"ingress": map[string]any{"host": c.AppHost(name)},
			"auth": map[string]any{
				"publicOrigin": "https://" + c.AppHost(name),
				"email": map[string]any{
					"provider":       "ses",
					"ses":            map[string]any{"region": c.Region},
					"from":           "Iterabase <no-reply@" + c.MailDomain + ">",
					"username":       smtpUsername,
					"existingSecret": SMTPSecretName,
					"passwordKey":    SMTPSecretKey,
				},
			},
		},
		"inference-gateway": map[string]any{
			"ingress": map[string]any{"host": c.GatewayHost(name)},
		},
	}
	out, err := yaml.Marshal(values)
	if err != nil {
		return nil, fmt.Errorf("hosted installation values: %w", err)
	}
	return append([]byte("# Generated by forge from the hosted baseline contract (HOR-593). Do not edit.\n"), out...), nil
}

// CloudflareSecret is the cluster's DNS token Secret, from the hosted-zone
// scoped SecureString (DES-HOR-601-03). It is applied over SSH stdin and never
// written to disk.
func (c *Contract) CloudflareSecret(namespace string) (string, error) {
	m := map[string]any{
		"apiVersion": "v1",
		"kind":       "Secret",
		"type":       "Opaque",
		"metadata": map[string]any{
			"name":      CloudflareSecretName,
			"namespace": namespace,
			"labels":    map[string]string{"app.kubernetes.io/managed-by": "forge"},
		},
		"stringData": map[string]string{CloudflareSecretKey: c.CloudflareDNSToken},
	}
	b, err := json.Marshal(m)
	return string(b), err
}

// SMTPSecret is the environment's SES SMTP password Secret, applied over SSH
// stdin and never written to disk.
func SMTPSecret(namespace, password string) (string, error) {
	m := map[string]any{
		"apiVersion": "v1",
		"kind":       "Secret",
		"type":       "Opaque",
		"metadata": map[string]any{
			"name":      SMTPSecretName,
			"namespace": namespace,
			"labels":    map[string]string{"app.kubernetes.io/managed-by": "forge"},
		},
		"stringData": map[string]string{SMTPSecretKey: password},
	}
	b, err := json.Marshal(m)
	return string(b), err
}
